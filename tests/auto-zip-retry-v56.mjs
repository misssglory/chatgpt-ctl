import assert from 'node:assert/strict';
import { nextZipAutoRetry, pendingZipCandidates, ZIP_AUTO_MAX_ATTEMPTS } from '../src/auto-zip-retry.mjs';
import { readFileSync } from 'node:fs';
const item = { identity: 'assistant-id|Hydra ETH Bundle v0.2.4.61', messageOrder: 6 };
assert.deepEqual(pendingZipCandidates([item], [], new Set([item.identity])), [item], 'pending survives turn advancement');
assert.deepEqual(pendingZipCandidates([item], [], new Set()), [], 'old zip is never reclassified as fresh');
const first = nextZipAutoRetry(undefined, 1000);
assert.equal(first.exhausted, false);
assert.equal(first.attempts, 1);
assert.ok(first.nextAt > 1000);
let retry = first;
for (let n = 2; n <= ZIP_AUTO_MAX_ATTEMPTS; n++) retry = nextZipAutoRetry(retry, retry.nextAt);
assert.equal(retry.exhausted, true);
const source = readFileSync(new URL('../src/index.ts', import.meta.url), 'utf8');
assert.ok(source.includes('pendingZipCandidates(observed, fresh, pendingIds)'));
assert.ok(source.includes('new Set([newest.identity])'), 'auto selection stays scoped to newest');
assert.ok(source.includes('pendingZipDownloads.set(hookKey, next)'));
assert.ok(!source.includes('handledHookDownloads.add(hookKey);\n                    try'), 'must not mark handled before download');
console.log('Auto ZIP retry tests passed');
