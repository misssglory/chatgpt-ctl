import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { snapshotBrowserDownloads, recoverBrowserDownload, expectedDownloadExtension } from '../src/download-fallback.mjs';
const root = await mkdtemp(path.join(os.tmpdir(), 'watcher-dl-test-'));
const downloads = path.join(root, 'Downloads');
const target = path.join(root, 'out');
const { mkdir } = await import('node:fs/promises');
await mkdir(downloads);
assert.equal(expectedDownloadExtension('the patched project ZIP'), '.zip');
const before = await snapshotBrowserDownloads([downloads]);
const zip = path.join(downloads, 'amnezia-patched.zip');
await writeFile(zip, Buffer.from([0x50, 0x4b, 3, 4, 0, 0, 0, 0]));
const recovered = await recoverBrowserDownload({ before, label: 'the patched project ZIP', directory: target, dirs: [downloads], sleep: async()=>{}, attempts: 2 });
assert(recovered?.endsWith('amnezia-patched.zip'));
assert.equal((await readFile(recovered))[0], 0x50);
const secondBefore = await snapshotBrowserDownloads([downloads]);
assert.equal(await recoverBrowserDownload({ before: secondBefore, label: 'the patched project ZIP', directory: target, dirs: [downloads], sleep: async()=>{}, attempts: 1 }), null);
const other = path.join(downloads, 'another.zip');
await writeFile(other, Buffer.from([0x50,0x4b,3,4,0,0]));
await writeFile(path.join(downloads,'third.zip'),Buffer.from([0x50,0x4b,3,4,0,0]));
assert.equal(await recoverBrowserDownload({ before: secondBefore, label: 'the patched project ZIP', directory: target, dirs: [downloads], sleep: async()=>{}, attempts: 1 }), null);
console.log('download-fallback-v61 passed');
